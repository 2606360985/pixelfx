// Original, code-drawn pixel artwork. No external image, likeness or font assets.
export function pixels(c) {
  const r = (x, y, w, h, color) => { c.fillStyle = color; c.fillRect(Math.round(x), Math.round(y), Math.max(1, Math.round(w)), Math.max(1, Math.round(h))); };
  const p = (points, color) => {
    const min = Math.floor(Math.min(...points.map(v => v[1]))), max = Math.ceil(Math.max(...points.map(v => v[1])));
    for (let y = min; y < max; y++) {
      const edges = [];
      for (let i = 0; i < points.length; i++) {
        const a = points[i], b = points[(i + 1) % points.length];
        if ((a[1] <= y + .5 && b[1] > y + .5) || (b[1] <= y + .5 && a[1] > y + .5)) edges.push(a[0] + (y + .5 - a[1]) / (b[1] - a[1]) * (b[0] - a[0]));
      }
      edges.sort((a, b) => a - b);
      for (let i = 0; i + 1 < edges.length; i += 2) r(Math.ceil(edges[i]), y, Math.max(1, Math.floor(edges[i + 1]) - Math.ceil(edges[i])), 1, color);
    }
  };
  const l = (x, y, tx, ty, color, width = 1) => {
    const n = Math.max(1, Math.ceil(Math.max(Math.abs(tx - x), Math.abs(ty - y))));
    for (let i = 0; i <= n; i++) r(x + (tx - x) * i / n, y + (ty - y) * i / n, width, width, color);
  };
  return { r, p, l };
}

